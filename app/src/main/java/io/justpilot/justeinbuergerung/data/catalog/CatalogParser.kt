package io.justpilot.justeinbuergerung.data.catalog

import io.justpilot.justeinbuergerung.domain.model.AnswerOption
import io.justpilot.justeinbuergerung.domain.model.Category
import io.justpilot.justeinbuergerung.domain.model.FederalState
import io.justpilot.justeinbuergerung.domain.model.LocalizedText
import io.justpilot.justeinbuergerung.domain.model.Question
import kotlinx.serialization.ExperimentalSerializationApi
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.decodeFromStream
import java.io.InputStream

/** The question catalog shipped as `assets/questions.json` (generated by tools/catalog). */
data class Catalog(val version: String, val questions: List<Question>)

object CatalogParser {
    const val ASSET_PATH = "questions.json"

    private val json = Json { ignoreUnknownKeys = true }

    @OptIn(ExperimentalSerializationApi::class)
    fun parse(input: InputStream): Catalog {
        val dto = input.use { json.decodeFromStream<CatalogDto>(it) }
        return Catalog(dto.catalogVersion, dto.questions.map { it.toDomain() })
    }

    @Serializable
    private data class CatalogDto(val catalogVersion: String, val questions: List<QuestionDto>)

    @Serializable
    private data class QuestionDto(
        val id: String,
        val number: Int,
        val state: String? = null,
        val category: String,
        val image: String? = null,
        val question: TextDto,
        val options: List<OptionDto>,
        @SerialName("correct_option") val correctOption: String,
    ) {
        fun toDomain(): Question {
            require(options.size == 4) { "Question $id must have 4 options, has ${options.size}" }
            require(options.any { it.id == correctOption }) { "Question $id: correct option $correctOption missing" }
            return Question(
                id = id,
                number = number,
                state = state?.let(FederalState::fromCode),
                category = Category.fromCode(category),
                imagePath = image,
                text = question.toDomain(),
                options = options.map { AnswerOption(it.id, it.text.toDomain()) },
                correctOptionId = correctOption,
            )
        }
    }

    @Serializable
    private data class OptionDto(val id: String, val text: TextDto)

    @Serializable
    private data class TextDto(val de: String, val en: String? = null, val uk: String? = null) {
        fun toDomain() = LocalizedText(german = de, english = en, ukrainian = uk)
    }
}
